#!/usr/bin/env python3
"""Convert assembler data includes (db/dw/dd lines) into C++ arrays.
usage: inc2cpp.py OUT.cpp NAME:TYPE:FILE.INC [NAME:TYPE:FILE.INC ...]
TYPE is int8_t/uint8_t/int16_t/uint16_t/int32_t."""
import re, sys


def num(tok):
    tok = tok.strip()
    neg = tok.startswith('-')
    if neg:
        tok = tok[1:].strip()
    if tok.lower().endswith('h'):
        v = int(tok[:-1], 16)
    elif tok.lower().startswith('0x'):
        v = int(tok, 16)
    elif tok.lower().endswith('b') and set(tok[:-1]) <= set('01'):
        v = int(tok[:-1], 2)
    else:
        v = int(tok)
    return -v if neg else v


def parse(path):
    """FILE[#START_LABEL[#END_LABEL]]: values between two LABEL lines"""
    start = end = None
    if '#' in path:
        parts = path.split('#')
        path, start = parts[0], parts[1]
        end = parts[2] if len(parts) > 2 else None
    vals = []
    on = start is None
    for line in open(path, encoding='latin1'):
        lab = re.match(r'^\s*(\w+)\s+LABEL', line, re.I)
        if lab:
            if start and lab.group(1).lower() == start.lower():
                on = True
                continue
            if end and lab.group(1).lower() == end.lower():
                on = False
        if not on:
            continue
        line = line.split(';')[0].strip()
        m = re.match(r'^(?:\w+\s+)?(db|dw|dd)\s+(.*)$', line, re.I)
        if not m:
            continue
        for tok in m.group(2).split(','):
            tok = tok.strip()
            if not tok:
                continue
            d = re.match(r'(\S+)\s+dup\s*\((.*)\)', tok, re.I)
            if d:
                inner = d.group(2).strip()
                vals += [0 if inner == '?' else num(inner)] * num(d.group(1))
            else:
                vals.append(num(tok))
    return vals


out = ['// generated by tools/inc2cpp.py - do not edit', '#include <stdint.h>']
for spec in sys.argv[2:]:
    name, typ, path = spec.split(':', 2)
    vals = parse(path)
    bits = {'int8_t': 8, 'uint8_t': 8, 'int16_t': 16, 'uint16_t': 16, 'int32_t': 32, 'uint32_t': 32}[typ]
    if typ.startswith('u'):
        vals = [v & ((1 << bits) - 1) for v in vals]
    else:
        vals = [((v + (1 << (bits - 1))) & ((1 << bits) - 1)) - (1 << (bits - 1)) for v in vals]
    out.append('extern const %s %s[%d];' % (typ, name, len(vals)))
    out.append('const %s %s[%d] = {' % (typ, name, len(vals)))
    for i in range(0, len(vals), 16):
        out.append('    ' + ', '.join(str(v) for v in vals[i:i + 16]) + ',')
    out.append('};')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
